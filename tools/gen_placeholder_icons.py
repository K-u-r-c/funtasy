#!/usr/bin/env python3
"""Draws placeholder icons / small sprites for every key in tools/placeholder_icons.json and
registers them in data/assets_placeholders.json (GameData merges data/assets.json over it, so a
key mapped to real art in assets.json always wins).

Usage (from the project root, needs ImageMagick `magick`):
    python3 tools/gen_placeholder_icons.py [--force]
    godot --headless --path . --import

Audio keys (groups "sfx" and "music") copy the file of an existing key ("like": "sfx.pickup") to
assets/audio/<group>/placeholder/gdd/<name>.wav; their "prompt" feeds the Suno list (docs/SUNO_PROMPTS.md).

Spec: {"<asset key>": {"color": "#rrggbb", "text": "Ab", "shape": "square" | "circle" |
"diamond" | "book" | "bar", "size": 32}}. Files go to assets/sprites/placeholder/gdd/<group>/<name>.png.
A key that data/assets.json already maps to real art is skipped, so the script is safe to re-run.
--force redraws existing placeholders.
"""
import json
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPEC = os.path.join(ROOT, "tools", "placeholder_icons.json")
ASSETS = os.path.join(ROOT, "data", "assets.json")
PLACEHOLDERS = os.path.join(ROOT, "data", "assets_placeholders.json")
OUT = "assets/sprites/placeholder/gdd"


def shade(hex_color, f):
    h = hex_color.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    return "#%02x%02x%02x" % tuple(max(0, min(255, int(c * f))) for c in (r, g, b))


def draw(path, spec):
    size = int(spec.get("size", 32))
    col = spec.get("color", "#888888")
    dark, light = shade(col, 0.45), shade(col, 1.35)
    shape = spec.get("shape", "square")
    s = size - 1
    if shape == "circle":
        body = ["-fill", col, "-stroke", dark, "-strokewidth", "2", "-draw", "circle %d,%d %d,%d" % (s // 2, s // 2, s // 2, 2)]
    elif shape == "diamond":
        body = ["-fill", col, "-stroke", dark, "-strokewidth", "2", "-draw",
                "polygon %d,1 %d,%d %d,%d 1,%d" % (s // 2, s - 1, s // 2, s // 2, s - 1, s // 2)]
    elif shape == "book":
        body = ["-fill", col, "-stroke", dark, "-strokewidth", "2", "-draw", "roundrectangle 5,3 %d,%d 2,2" % (s - 5, s - 3),
                "-fill", light, "-stroke", "none", "-draw", "rectangle 7,%d %d,%d" % (s - 7, s - 7, s - 5)]
    elif shape == "bar":
        body = ["-fill", col, "-stroke", dark, "-strokewidth", "2", "-draw", "roundrectangle 2,%d %d,%d 3,3" % (s // 3, s - 2, s - s // 3)]
    else:
        body = ["-fill", col, "-stroke", dark, "-strokewidth", "2", "-draw", "roundrectangle 2,2 %d,%d 4,4" % (s - 2, s - 2)]
    text = spec.get("text", "")
    cmd = ["magick", "-size", "%dx%d" % (size, size), "xc:none"] + body
    if text:
        pt = max(7, int(size * (0.5 if len(text) == 1 else 0.36)))
        cmd += ["-font", "DejaVu-Sans-Bold", "-pointsize", str(pt), "-gravity", "center",
                "-fill", "#101010", "-stroke", "none", "-annotate", "+1+1", text,
                "-fill", "#fff6dc", "-annotate", "+0+0", text]
    cmd += ["+antialias", path]
    subprocess.run(cmd, check=True)


def main():
    force = "--force" in sys.argv
    spec = json.load(open(SPEC))
    assets = json.load(open(ASSETS))
    out = {"_comment": "Generated by tools/gen_placeholder_icons.py from tools/placeholder_icons.json. Do not edit: put real art in data/assets.json (it overrides these keys)."}
    drawn = 0
    for key, sp in spec.items():
        if key.startswith("_"):
            continue
        group, name = key.split(".", 1)
        audio = group in ("sfx", "music")
        if audio:
            rel = "assets/audio/%s/placeholder/gdd/%s.wav" % (group, name)
        else:
            rel = "%s/%s/%s.png" % (OUT, group, name.replace(".", "_"))
        existing = assets.get(group, {}).get(name)
        existing_path = existing.get("path") if isinstance(existing, dict) else existing
        if existing_path:
            continue  # assets.json already maps it (real art or an older placeholder)
        path = os.path.join(ROOT, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        if force or not os.path.exists(path):
            if audio:
                lg, ln = sp["like"].split(".", 1)
                src = assets[lg][ln]
                shutil.copyfile(os.path.join(ROOT, (src["path"] if isinstance(src, dict) else src).replace("res://", "")), path)
            else:
                draw(path, sp)
            drawn += 1
        out.setdefault(group, {})[name] = "res://" + rel
    with open(PLACEHOLDERS, "w") as f:
        json.dump(out, f, indent="\t", ensure_ascii=False, sort_keys=True)
        f.write("\n")
    print("placeholders: %d drawn, %d keys in spec" % (drawn, len([k for k in spec if not k.startswith("_")])))


if __name__ == "__main__":
    main()
