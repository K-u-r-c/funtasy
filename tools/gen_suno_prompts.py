#!/usr/bin/env python3
"""Writes docs/SUNO_PROMPTS.md: every music / sfx key the game plays, the exact file path to drop
your own audio at, what uses it, and a prompt to write it (Suno for music, any SFX tool for effects).

Usage (from the project root):
    python3 tools/gen_suno_prompts.py
Prompts come from tools/placeholder_icons.json (the newer keys) and BASE_PROMPTS below (MVP keys).
"""
import glob
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

BASE_PROMPTS = {
    "music.menu": "Dark fantasy main menu theme, slow and melancholic: solo cello over a low string pad, distant choir, soft bells, a hint of hope; 90 s seamless loop, instrumental",
    "music.crypt": "Dark fantasy dungeon ambience, forgotten crypt: low droning strings, distant dripping water, faint male choir hums, sparse bell tolls, cold and oppressive; 2-3 min seamless loop, instrumental",
    "music.boss_bone_lord": "Dark fantasy boss battle, ancient bone lord (legacy MVP boss, kept as a fallback): driving war drums, low brass stabs, chanting choir; 2 min seamless loop, instrumental",
    "sfx.break": "wooden crate or barrel smashing into splinters, short, dry",
    "sfx.buff": "rising magical shimmer with a soft warm chord, short positive buff",
    "sfx.cast": "short arcane whoosh with sparkling release, generic spell cast",
    "sfx.crit": "heavy meaty critical hit impact with a sharp metallic ring",
    "sfx.dash": "fast cloth and air whoosh of a quick dodge roll",
    "sfx.death": "monster death groan fading out, guttural, short",
    "sfx.door": "heavy wooden dungeon door creaking open on iron hinges",
    "sfx.enemy_hit": "blade hitting flesh and leather armor, short thud",
    "sfx.equip": "armor buckle and chainmail rustle as gear is put on",
    "sfx.explosion": "barrel explosion, deep boom with debris and crackling fire tail",
    "sfx.fire": "fireball launch, roaring burst of flame",
    "sfx.frost": "ice spell, crackling frost and shattering crystal",
    "sfx.heal": "gentle holy healing chime with a warm rising choir note",
    "sfx.hit": "hero taking a hit, dull impact with a short grunt",
    "sfx.level_up": "triumphant short fanfare of bells and choir, level up",
    "sfx.lightning": "sharp electric crack and sizzling thunder snap",
    "sfx.pickup": "small item picked up, leather and a soft metallic clink",
    "sfx.portal": "magical portal opening, deep swirling hum with a rising shimmer",
    "sfx.potion": "drinking a potion: cork pop, two gulps, glass clink",
    "sfx.revive": "holy resurrection, bright choir swell and a heartbeat",
    "sfx.roar": "huge monster roar, deep and echoing in a stone hall",
    "sfx.shoot": "bow string release and arrow whistle",
    "sfx.spikes": "iron floor spikes shooting out of stone with a metallic shing",
    "sfx.swing": "heavy weapon swing whoosh",
    "sfx.ui_accept": "UI confirm, soft stone click with a small bright chime",
    "sfx.ui_back": "UI back, muted low click",
    "sfx.ui_drop": "UI item dropped, soft leather thud",
    "sfx.ui_error": "UI error, dull low buzz, short",
    "sfx.ui_move": "UI focus move, very short quiet tick",
    "sfx.ui_open": "UI window opening, parchment unfurl with a faint chime",
    "sfx.ui_press": "UI button press, short crisp click",
}


def main():
    keys = {"music": {}, "sfx": {}}
    for f in ("data/assets.json", "data/assets_placeholders.json"):
        path = os.path.join(ROOT, f)
        if os.path.exists(path):
            data = json.load(open(path))
            for g in keys:
                for k in data.get(g, {}):
                    keys[g].setdefault(k, "")
    spec = json.load(open(os.path.join(ROOT, "tools", "placeholder_icons.json")))
    for k, v in list(spec.items()) + [(k, {"prompt": p}) for k, p in BASE_PROMPTS.items()]:
        g, _, n = k.partition(".")
        if g in keys and isinstance(v, dict) and v.get("prompt"):
            keys[g][n] = keys[g].get(n) or v["prompt"]
    # Who plays each key (data files only; UI / engine sounds are listed as "engine").
    users = {}
    for f in sorted(glob.glob(os.path.join(ROOT, "data", "**", "*.json"), recursive=True)):
        rel = os.path.relpath(f, ROOT)
        if os.path.basename(f).startswith("assets"):
            continue
        text = open(f).read()
        for m in re.finditer(r'"(music|boss_music|sfx|sound)":\s*"([a-z0-9_]+)"', text):
            g = "music" if "music" in m.group(1) else "sfx"
            users.setdefault((g, m.group(2)), set()).add(rel.replace("data/", ""))
    out = ["# Audio keys and prompts", "",
           "Generated by `tools/gen_suno_prompts.py` - do not edit by hand.", "",
           "Every sound in the game is a key in `data/assets.json` (groups `music` and `sfx`). Placeholders are",
           "generated silence / tones. To use your own file:", "",
           "1. Save it as `assets/audio/music/<key>.ogg` (or `.mp3` / `.wav`) for music, `assets/audio/sfx/<key>.ogg`",
           "   (or `.wav`) for effects - the file name is the key below.",
           "2. Run `python3 tools/register_audio.py` (points the key at your file; nothing is moved or deleted).",
           "3. Open the project once in the editor (or `godot --headless --path . --import`).", "",
           "Music loops: make each track loop seamlessly (Suno: \"instrumental, seamless loop\"); the game crossfades",
           "between the floor track and the boss track. Effects: short (0.2-1.5 s), dry, mono is fine.", ""]
    for g, title in (("music", "Music (Suno)"), ("sfx", "Sound effects")):
        out += ["## " + title, "", "| Key | File | Used by | Prompt |", "| --- | --- | --- | --- |"]
        for k in sorted(keys[g]):
            used = ", ".join(sorted(users.get((g, k), []))[:4]) or ("menus / lobby" if k == "menu" else "engine")
            if (g, k) == ("music", "boss_bone_lord"):
                used = "legacy fallback (no boss uses it)"
            ext = "ogg"
            out.append("| `%s` | `assets/audio/%s/%s.%s` | %s | %s |" % (k, g, k, ext, used, keys[g][k] or "-"))
        out.append("")
    open(os.path.join(ROOT, "docs", "SUNO_PROMPTS.md"), "w").write("\n".join(out))
    print("docs/SUNO_PROMPTS.md: %d music, %d sfx" % (len(keys["music"]), len(keys["sfx"])))


if __name__ == "__main__":
    main()
